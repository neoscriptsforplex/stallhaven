-- Lets a signed-in player delete their account and every online save.
-- SECURITY DEFINER so it can remove the caller's auth.users row; it only ever
-- touches auth.uid(), so a caller can delete nobody but themselves.
create or replace function public.delete_my_account()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
begin
  if uid is null then
    raise exception 'not signed in' using errcode = '42501';
  end if;
  delete from public.saves where user_id = uid;
  delete from auth.users where id = uid;
end;
$$;

revoke all on function public.delete_my_account() from public, anon;
grant execute on function public.delete_my_account() to authenticated;
